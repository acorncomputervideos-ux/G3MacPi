def main():
    chars = [chr(c) for c in range(0x20, 0x7F)]
    missing = [c for c in chars if c not in G]
    if missing:
        sys.exit("missing glyphs: %r" % missing)
    out = ["// SPDX-License-Identifier: GPL-3.0-or-later",
           "// Generated by tools/font/make_font.py — edit the drawings there, not this file.",
           "// 95 glyphs (0x20-0x7E), 8 rows each; bit 7 = leftmost pixel.", ""]
    for c in chars:
        rows = []
        for r in G[c]:
            v = 0
            for i, p in enumerate(r):
                if p == '#':
                    v |= 0x80 >> i
            rows.append("0x%02X" % v)
        name = {'\\': 'backslash', "'": 'quote', '"': 'dquote'}.get(c, c)
        out.append("    {%s},  // 0x%02X %s" % (", ".join(rows), ord(c), name))
    path = "core/firmware/openfirm/font8x8.inc"
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", path)

if __name__ == "__main__":
    main()
