ROWS = 12


def bits(row):
    v = 0
    for x, c in enumerate(row):
        if c == '#':
            v |= 1 << x
    return v


def main():
    missing = [chr(c) for c in range(0x20, 0x7F) if chr(c) not in G]
    assert not missing, missing
    out = []
    out.append("// SPDX-License-Identifier: GPL-3.0-or-later")
    out.append("// Generated by tools/font/make_ui_font.py: do not edit.")
    out.append("// The settings menu's font, 0x20-0x7E: {width, rows[12]}, bit x = column x.")
    for c in range(0x20, 0x7F):
        rows = G[chr(c)]
        w = len(rows[0])
        assert all(len(r) == w for r in rows), (chr(c), rows)
        bold = [bits(r) | (bits(r) << 1) for r in rows] if c != 0x20 else [0] * ROWS
        bw = w + 1 if c != 0x20 else w
        out.append("    {%d, {%s}},  // %r" % (bw, ", ".join("0x%04X" % b for b in bold), chr(c)))
    with open("platform/common/ui_font.inc", "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
