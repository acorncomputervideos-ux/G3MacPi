"""Generates platform/common/ui_font.inc: the settings menu's font.

A proportional bitmap font in the spirit of the classic Macintosh system
font (heavy two-pixel verticals, one-pixel horizontals, 12 pixels tall),
designed for this project: each glyph is drawn below with one-pixel
strokes ('#' = ink) on 12 rows (rows 0-8 caps and ascenders, rows 9-11
descenders; the baseline is under row 8), then emboldened by also inking
the pixel to the right of every ink pixel. Run from the repository root:
    python3 tools/font/make_ui_font.py
"""

G = {}
E3 = ["", "", ""]


def norm(rows):
    w = max(len(r) for r in rows) if rows else 0
    return [r.ljust(w, '.') for r in rows]


def cap(*rows):            # 9 rows from the top, nothing below the baseline
    assert len(rows) == 9, rows
    return list(rows) + ["", "", ""]


def low(*rows):            # x-height glyph: 6 rows (3-8), optional 3 descender rows
    assert len(rows) in (6, 9), rows
    return ["", "", ""] + list(rows) + ([] if len(rows) == 9 else ["", "", ""])


def g(ch, rows, width=None):
    rows = list(rows)
    assert len(rows) == 12, (ch, len(rows))
    w = width if width is not None else max(len(r) for r in rows)
    G[ch] = [r.ljust(w, '.') for r in rows]


