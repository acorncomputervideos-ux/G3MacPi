# tools/embed_ndrv.py — writes app/circle/ndrv_data.cpp: our display driver
# (a PEF file built by the host CMake build) as a C array for the Pi
# kernel. With no PEF, writes an empty array (Mac OS then cannot draw).
#
#   embed_ndrv.py <g3_ndrv.pef or ""> <out.cpp>

import os
import sys

pef, out = sys.argv[1], sys.argv[2]
data = open(pef, 'rb').read() if pef and os.path.exists(pef) else b''
lines = ['// Generated by tools/embed_ndrv.py from %s - do not edit.' % (os.path.basename(pef) if data else '(no driver)'),
         '#include "ndrv_data.h"',
         '',
         'alignas(16) const unsigned char g_NdrvData[%d] = {' % max(len(data), 1)]
for i in range(0, len(data), 16):
    lines.append('\t' + ', '.join('0x%02X' % b for b in data[i:i + 16]) + ',')
if not data:
    lines.append('\t0')
lines += ['};', 'const unsigned g_NdrvSize = %d;' % len(data), '']
text = '\n'.join(lines)
if not os.path.exists(out) or open(out).read() != text:  # keep the timestamp when unchanged
    open(out, 'w').write(text)
print('%s: %d bytes of display driver' % (out, len(data)))
