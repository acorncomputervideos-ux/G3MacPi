# Regenerates tests/unit/cpu/a64_golden.inc from tests/unit/cpu/a64_cases.inc:
# each case's text is assembled on its own by the GNU AArch64 assembler, and
# its first instruction word recorded. Needs aarch64-none-elf-as/objcopy
# (the Arm GNU toolchain used for the Pi build), e.g.:
#   PATH=/opt/toolchains/arm-gnu-toolchain-*/bin:$PATH tools/jit/a64_vectors.sh
set -e
cd "$(dirname "$0")/../.."
cases=tests/unit/cpu/a64_cases.inc
out=tests/unit/cpu/a64_golden.inc
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
{
    echo "// SPDX-License-Identifier: GPL-3.0-or-later"
    echo "// Generated by tools/jit/a64_vectors.sh from a64_cases.inc with $(aarch64-none-elf-as --version | head -1)."
    echo "// Do not edit."
} > "$tmp/out"
grep '^CASE("' "$cases" | sed 's/^CASE("\([^"]*\)".*/\1/' | while IFS= read -r text; do
    printf '%s\n' "$text" > "$tmp/c.s"
    aarch64-none-elf-as -o "$tmp/c.o" "$tmp/c.s"
    aarch64-none-elf-objcopy -O binary -j .text "$tmp/c.o" "$tmp/c.bin"
    word=$(od -An -tx4 -N4 "$tmp/c.bin" | tr -d ' ')
    printf 'GOLDEN("%s", 0x%s)\n' "$text" "$word" >> "$tmp/out"
done
mv "$tmp/out" "$out"
echo "wrote $out ($(grep -c GOLDEN "$out") encodings)"
